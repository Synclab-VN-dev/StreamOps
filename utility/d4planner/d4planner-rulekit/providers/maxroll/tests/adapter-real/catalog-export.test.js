const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const base=path.resolve(__dirname,'../..');
const api=require(base+'/src');
require('node:test')('RK-CAT real offline snapshot export', async t=>{
 assert.ok(process.env.MAXROLL_AUTHORIZED_SNAPSHOT_ROOT, 'private snapshot root required');
 const dir=await fs.mkdtemp(require('node:os').tmpdir()+'/catalog-real-');
 t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 const options={snapshotRoot:process.env.MAXROLL_AUTHORIZED_SNAPSHOT_ROOT,snapshotId:api.D12_COMPATIBILITY.snapshotId,expectedManifestSha256:api.D12_COMPATIBILITY.snapshotManifestSha256};
 const full=await api.exportMaxrollGameDataCatalog({...options,outputPath:dir+'/full.json'});
 await api.exportMaxrollGameDataCatalog({...options,outputPath:dir+'/second.json'});
 assert.deepEqual(await fs.readFile(dir+'/full.json'),await fs.readFile(dir+'/second.json'));
 const doc=JSON.parse(await fs.readFile(dir+'/full.json'));
 const inventory=await api.listMaxrollCatalogFamilies(options);
 assert.deepEqual(full.familyCounts,inventory.families);
 assert.equal(inventory.familyCount,16);
 const source=await api.loadMaxrollEntityCatalog(options);
 assert.deepEqual(doc.families,source.exportFamilies());
 const subset=await api.exportMaxrollGameDataCatalog({...options,families:['items','skills','paragonBoards'],outputPath:dir+'/subset.json'});
 assert.equal(Object.keys(subset.familyCounts).length,3);
 assert.equal((await fs.stat(dir+'/full.json')).mode&0o777,0o600);
 await assert.rejects(api.exportMaxrollGameDataCatalog({...options,outputPath:dir+'/full.json'}),{code:'OUTPUT_EXISTS'});
 for(const patch of [{expectedManifestSha256:'0'.repeat(64)},{snapshotId:'missing'},{families:['gems']},{snapshotRoot:'/nonexistent'}]) await assert.rejects(api.exportMaxrollGameDataCatalog({...options,...patch,outputPath:dir+'/bad.json'}));
 await assert.rejects(fs.access(dir+'/bad.json'));
 const {execFileSync,spawnSync}=require('node:child_process');
 const cli=base+'/scripts/catalog-export.js';
 const args=['--snapshot-root',options.snapshotRoot,'--snapshot-id',options.snapshotId,'--manifest-sha256',options.expectedManifestSha256];
 assert.deepEqual(JSON.parse(execFileSync(process.execPath,[cli,...args,'--list-families'])),inventory);
 assert.equal(spawnSync(process.execPath,[cli,...args,'--families','gems','--output',dir+'/bad.json']).status,1);
});
